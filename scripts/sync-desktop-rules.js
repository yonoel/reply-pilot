import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "src", "approval", "instruction-rules.js");
const targetPath = join(root, "desktop", "instruction-rules.generated.js");

const source = readFileSync(sourcePath, "utf8");
writeFileSync(targetPath, `// Generated by scripts/sync-desktop-rules.js. Do not edit by hand.\n${source}`);
